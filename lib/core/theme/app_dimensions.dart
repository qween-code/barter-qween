  /// Responsive spacing hesapla
  static double calculateResponsiveSpacing({
    required double baseSpacing,
    required double screenWidth,
    double scaleFactor = 1.0,
  }) {
    final responsiveValue = baseSpacing * (screenWidth / 375) * scaleFactor;
    return responsiveValue.clamp(baseSpacing * 0.5, baseSpacing * 2.0);
  }

  /// Component boyutunu hesapla
  static double calculateComponentSize({
    required double baseSize,
    required String componentType,
    double scaleFactor = 1.0,
  }) {
    final multiplier = switch (componentType) {
      'button' => 1.0,
      'input' => 1.1,
      'card' => 1.2,
      'avatar' => 0.9,
      'icon' => 0.8,
      _ => 1.0,
    };

    return baseSize * multiplier * scaleFactor;
  }
